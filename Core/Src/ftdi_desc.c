// 字符串描述符(bLength=2+2*字符数)
const uint8_t ftdi_str0[4]  = { 0x04, 0x03, 0x09, 0x04 };
const uint8_t ftdi_str1[16] = { 0x10, 0x03,
    'A',0,'n',0,'l',0,'o',0,'g',0,'i',0,'c',0 };                            // 厂商: Anlogic
const uint8_t ftdi_str2[30] = { 0x1E, 0x03,
    'U',0,'S',0,'B',0,'-',0,'J',0,'T',0,'A',0,'G',0,' ',0,
    'C',0,'a',0,'b',0,'l',0,'e',0 };                                        // 产品: USB-JTAG Cable
const uint8_t ftdi_str3[22] = { 0x16, 0x03,
    'A',0,'L',0,'F',0,'T',0,'9',0,'C',0,'F',0,'0',0,'D',0,'A',0 };          // 序列号

int ftdi_get_descriptor(uint8_t speed, uint16_t wValue,
                        const uint8_t **pptr, uint16_t *plen)
{
    uint8_t type = (uint8_t)(wValue >> 8);
    uint8_t idx  = (uint8_t)(wValue & 0xFF);
    const uint8_t *p = 0;
    uint16_t len = 0;

    switch (type) {
        case 0x01:  // DEVICE
            p = ftdi_devdesc; len = 18;
            break;
        case 0x02:  // CONFIG: USBHS口5接口(按速率选包长)
            p = speed ? ftdi_cfg_hs : ftdi_cfg_hs_fs; len = 124;
            break;
        case 0x03:  // STRING
            switch (idx) {
                case 0:  p = ftdi_str0; len = 4;  break;
                case 1:  p = ftdi_str1; len = 16; break;
                case 2:  p = ftdi_str2; len = 30; break;
                case 3:  p = ftdi_str3; len = 22; break;
                default: return 0xFF;
            }
            break;
        case 0x06:  // DEVICE_QUALIFIER
            p = ftdi_qualdesc; len = 10;
            break;
        case 0x07:  // OTHER_SPEED: 同一HS设备的另一种速度形态
            p = speed ? ftdi_osc_from_hs : ftdi_cfg_hs; len = 124;
            break;
        case 0x0F:  // BOS, USB2.0设备不支持
        default:
            return 0xFF;
    }
    *pptr = p;
    *plen = len;
    return 0;
}

// 假EEPROM: 模拟一块写好参数的93C66(FT4232H配256字EEPROM)
// 布局参考ftx-prog: 头部+字符串, 工具读起来不报错就行
uint16_t ftdi_eeprom_word(uint16_t addr)
{
    addr &= 0xFF;
    switch (addr) {
        case 0:  return 0x0800;   // 通道A属性(有大电流驱动位之类)
        case 1:  return 0x0403;   // VID
        case 2:  return 0x6042;   // PID
        case 3:  return 0x0700;   // bcdDevice
        case 4:  return 0x0800;   // 通道B属性
        case 5:  return 0x0000;   // USB属性: 总线供电
        case 6:  return 0x0800;   // 通道C属性
        case 7:  return 0x0800;   // 通道D属性
        default: return 0x0000;
    }
}
